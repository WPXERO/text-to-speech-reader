#!/usr/bin/env node
/**
 * Regenerates src/admin-ui/icon-data.ts from Material Symbols Rounded
 * (weight 400, Apache License 2.0). The icon package is large, so it is not
 * a devDependency; install it temporarily first:
 *
 *   npm install --no-save `@material-symbols/svg-400`
 *   node bin/icons.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname( path.dirname( fileURLToPath( import.meta.url ) ) );
const SOURCE = path.join(
	process.env.ICONS_DIR ||
		path.join( ROOT, 'node_modules/@material-symbols/svg-400' ),
	'rounded'
);
const OUT = path.join( ROOT, 'src/admin-ui/icon-data.ts' );

// Icons with a filled variant used for active and emphasised states.
const FILLED = new Set( [
	'article',
	'check_box',
	'check_circle',
	'dashboard_customize',
	'error',
	'extension',
	'graphic_eq',
	'headphones',
	'help',
	'info',
	'ink_highlighter',
	'lock',
	'palette',
	'pause',
	'play_arrow',
	'record_voice_over',
	'rule',
	'smart_display',
	'space_dashboard',
	'stop',
	'swap_vert',
	'tune',
	'warning',
	'workspace_premium',
] );

const NAMES = [
	...FILLED,
	'add',
	'arrow_forward',
	'block',
	'bolt',
	'build',
	'check',
	'check_box_outline_blank',
	'close',
	'code',
	'content_copy',
	'database',
	'description',
	'do_not_disturb_on',
	'download',
	'edit_square',
	'keyboard_arrow_down',
	'label',
	'my_location',
	'open_in_new',
	'public',
	'radio_button_checked',
	'radio_button_unchecked',
	'remove',
	'shield',
	'speed',
	'storefront',
	'text_select_start',
	'toggle_on',
	'translate',
	'upload',
	'upload_file',
	'vertical_align_center',
	'visibility',
	'widgets',
].sort();

const read = ( file ) => {
	const svg = readFileSync( path.join( SOURCE, file ), 'utf8' );
	const paths = [ ...svg.matchAll( /\sd="([^"]+)"/g ) ].map(
		( m ) => m[ 1 ]
	);
	if ( ! paths.length ) {
		throw new Error( `no path in ${ file }` );
	}
	return paths.join( '' );
};

if ( ! existsSync( SOURCE ) ) {
	console.error(
		`${ SOURCE } not found. Run: npm install --no-save @material-symbols/svg-400`
	);
	process.exit( 1 );
}

const lines = NAMES.map( ( name ) => {
	const outline = read( `${ name }.svg` );
	const fill = FILLED.has( name ) ? read( `${ name }-fill.svg` ) : '';
	const value =
		fill && fill !== outline
			? `[ '${ outline }', '${ fill }' ]`
			: `[ '${ outline }' ]`;
	return `\t${ name }: ${ value },`;
} );

writeFileSync(
	OUT,
	`/**
 * Generated by bin/icons.mjs — do not edit.
 *
 * Material Symbols Rounded, weight 400, viewBox "0 -960 960 960".
 * Copyright Google LLC, Apache License 2.0.
 * https://github.com/google/material-design-icons
 *
 * Each entry is [ outline path, filled path? ].
 */
// prettier-ignore
export const ICON_DATA = {
${ lines.join( '\n' ) }
} as const;
`
);
console.log( `${ NAMES.length } icons → ${ path.relative( ROOT, OUT ) }` );
