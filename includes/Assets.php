<?php
/**
 * Script and style registration.
 *
 * @package TTSR
 */

namespace TTSR;

defined( 'ABSPATH' ) || exit;

/**
 * Registers the built bundles and enqueues the frontend player on demand.
 */
final class Assets {

	const PLAYER_HANDLE = 'ttsr-player';

	/**
	 * Admin UI library (`window.ttsr.adminUi`), shared with extensions.
	 */
	const ADMIN_UI_HANDLE = 'ttsr-admin-ui';

	/**
	 * Whether the player assets were enqueued in this request.
	 *
	 * @var bool
	 */
	private $player_enqueued = false;

	/**
	 * Hooks asset registration.
	 */
	public function register_hooks() {
		add_action( 'init', array( $this, 'register' ), 5 );
	}

	/**
	 * Dependencies and version generated by the build for an entry point.
	 *
	 * @param string $entry Entry name, e.g. `player`.
	 * @return array{dependencies: string[], version: string}
	 */
	public static function asset( $entry ) {
		$file  = TTSR_PATH . 'build/' . $entry . '.asset.php';
		$asset = is_readable( $file ) ? require $file : array();
		return array(
			'dependencies' => isset( $asset['dependencies'] ) ? $asset['dependencies'] : array(),
			'version'      => isset( $asset['version'] ) ? $asset['version'] : TTSR_VERSION,
		);
	}

	/**
	 * Registers a built script, and its stylesheet when the build emitted one.
	 *
	 * @param string $handle Handle for both the script and the style.
	 * @param string $entry  Entry name.
	 * @param array  $args   Extra wp_register_script() arguments.
	 * @param array  $deps   Extra script dependencies.
	 */
	public static function register_entry( $handle, $entry, array $args = array(), array $deps = array() ) {
		$asset = self::asset( $entry );
		wp_register_script(
			$handle,
			TTSR_URL . 'build/' . $entry . '.js',
			array_merge( $asset['dependencies'], $deps ),
			$asset['version'],
			array_merge( array( 'in_footer' => true ), $args )
		);
		if ( is_readable( TTSR_PATH . 'build/' . $entry . '.css' ) ) {
			wp_register_style( $handle, TTSR_URL . 'build/' . $entry . '.css', array(), $asset['version'] );
			wp_style_add_data( $handle, 'rtl', 'replace' );
		}
		if ( in_array( 'wp-i18n', $asset['dependencies'], true ) ) {
			wp_set_script_translations( $handle, 'wpxero-text-to-speech', TTSR_PATH . 'languages' );
		}
	}

	/**
	 * Registers every handle. Nothing is enqueued here.
	 */
	public function register() {
		self::register_entry( self::PLAYER_HANDLE, 'player', array( 'strategy' => 'defer' ) );
		wp_add_inline_script(
			self::PLAYER_HANDLE,
			'window.ttsrPlayerSettings = ' . wp_json_encode(
				array(
					'version' => TTSR_VERSION,
					'strings' => $this->player_strings(),
				)
			) . ';',
			'before'
		);

		self::register_entry( self::ADMIN_UI_HANDLE, 'admin-ui' );
		self::register_entry( 'ttsr-block-editor', 'block' );
		self::register_entry( 'ttsr-editor', 'editor' );
	}

	/**
	 * Enqueues the frontend player once per request.
	 */
	public function enqueue_player() {
		if ( $this->player_enqueued ) {
			return;
		}
		$this->player_enqueued = true;
		wp_enqueue_script( self::PLAYER_HANDLE );
		wp_enqueue_style( self::PLAYER_HANDLE );

		if ( ! is_admin() ) {
			/**
			 * Fires when the player assets are enqueued on a public page.
			 *
			 * Extensions should enqueue their frontend assets here so they
			 * load only on pages that actually show a player.
			 *
			 * @since 1.0.0
			 */
			do_action( 'ttsr_enqueue_player_assets' );
		}
	}

	/**
	 * Translated strings for the player.
	 *
	 * @return array<string, string>
	 */
	public function player_strings() {
		return array(
			'ready'            => '',
			'loading'          => __( 'Loading voices…', 'wpxero-text-to-speech' ),
			'playing'          => __( 'Playing', 'wpxero-text-to-speech' ),
			'paused'           => __( 'Paused', 'wpxero-text-to-speech' ),
			'stopped'          => __( 'Stopped', 'wpxero-text-to-speech' ),
			'finished'         => __( 'Finished', 'wpxero-text-to-speech' ),
			'empty'            => __( 'There is no text to read here.', 'wpxero-text-to-speech' ),
			'unsupported'      => __( 'Your browser does not support text to speech.', 'wpxero-text-to-speech' ),
			'error'            => __( 'Speech could not be played in this browser.', 'wpxero-text-to-speech' ),
			'voice'            => __( 'Voice', 'wpxero-text-to-speech' ),
			'speed'            => __( 'Speed', 'wpxero-text-to-speech' ),
			'defaultVoice'     => __( 'Default voice', 'wpxero-text-to-speech' ),
			/* translators: 1: current part number, 2: total number of parts. */
			'progress'         => __( 'Part %1$d of %2$d', 'wpxero-text-to-speech' ),
			'region'           => __( 'Listen to this content', 'wpxero-text-to-speech' ),
			'matchingLanguage' => __( 'Matching language', 'wpxero-text-to-speech' ),
			'otherLanguages'   => __( 'Other languages', 'wpxero-text-to-speech' ),
		);
	}
}
